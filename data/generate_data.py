def build_records(items):
    # id is a zero-padded string so it sorts/reads nicely and matches
    # DynamoDB's string primary key type used in the seed script.
    return [{"id": str(i + 1), "text": text} for i, text in enumerate(items)]


def main():
    assert len(TRUTHS) >= 100, f"Need >=100 truths, got {len(TRUTHS)}"
    assert len(DARES) >= 100, f"Need >=100 dares, got {len(DARES)}"
    assert len(set(TRUTHS)) == len(TRUTHS), "Duplicate truth found!"
    assert len(set(DARES)) == len(DARES), "Duplicate dare found!"

    out_dir = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(out_dir, "truths.json"), "w") as f:
        json.dump(build_records(TRUTHS), f, indent=2)
    with open(os.path.join(out_dir, "dares.json"), "w") as f:
        json.dump(build_records(DARES), f, indent=2)

    print(f"Wrote {len(TRUTHS)} truths and {len(DARES)} dares.")


if __name__ == "__main__":
    main()
